        static readonly Dictionary<char, (char baseChar, string accent)> Accented = new Dictionary<char, (char, string)>
        {
            ['Á'] = ('A', "...#."), ['É'] = ('E', "...#."), ['Í'] = ('I', "...#."),
            ['Ó'] = ('O', "...#."), ['Ú'] = ('U', "...#."), ['Ñ'] = ('N', ".####"),
        };

        public static void Build()
        {
            if (Atlas != null) return;
            int count = Glyphs.Count + Accented.Count;
            int rows = (count + Columns - 1) / Columns;
            int w = Columns * CellW, h = rows * CellH;
            var px = new Color32[w * h];

            int index = 0;
            void Paint(char ch, string[] rowsTopDown, string accent)
            {
                int cx = (index % Columns) * CellW, cy = (index / Columns) * CellH;
                for (int r = 0; r < 7; r++)
                    for (int c = 0; c < GlyphW; c++)
                        if (rowsTopDown[r][c] == '#') px[(cy + 6 - r) * w + cx + c] = new Color32(255, 255, 255, 255);
                if (accent != null)
                    for (int c = 0; c < GlyphW; c++)
                        if (accent[c] == '#') px[(cy + 7) * w + cx + c] = new Color32(255, 255, 255, 255);
                uv[ch] = new Rect(cx / (float)w, cy / (float)h, GlyphW / (float)w, GlyphH / (float)h);
                index++;
            }

            foreach (var kv in Glyphs) Paint(kv.Key, kv.Value, null);
            foreach (var kv in Accented) Paint(kv.Key, Glyphs[kv.Value.baseChar], kv.Value.accent);

            Atlas = new Texture2D(w, h, TextureFormat.RGBA32, false)
            {
                name = "PixelFontAtlas",
                filterMode = FilterMode.Point,
                wrapMode = TextureWrapMode.Clamp,
            };
            Atlas.SetPixels32(px);
            Atlas.Apply(false, true);
        }

        public static bool TryGet(char c, out Rect rect)
        {
            c = Normalize(c);
            return uv.TryGetValue(c, out rect);
        }

        public static char Normalize(char c)
        {
            c = char.ToUpperInvariant(c);
            switch (c)
            {
                case 'À': case 'Ä': case 'Â': return 'A';
                case 'È': case 'Ë': case 'Ê': return 'E';
                case 'Ì': case 'Ï': return 'I';
                case 'Ò': case 'Ö': return 'O';
                case 'Ù': case 'Ü': return 'U';
                default: return c;
            }
        }

        /// <summary>Width in font pixels (before scaling) of the widest line.</summary>
        public static int Measure(string text)
        {
            int best = 0, cur = 0;
            foreach (char ch in text)
            {
                if (ch == '\n') { best = Mathf.Max(best, cur); cur = 0; continue; }
                cur += ch == ' ' ? 4 : CellW;
            }
            return Mathf.Max(best, cur) - (cur > 0 ? 1 : 0);
        }
